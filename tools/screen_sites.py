# Classify MAIN.EXE's 640/480/400 immediates into run_lift.py's SCREEN_SITES.
# Reads the lifted C (comments carry the instructions); prints the table:
#   py tools/screen_sites.py > sites.txt, then paste over the generated block.
# Re-run after a change to the rules below; the lift itself does not run it.
import os, re, glob
ins = {}
GEN = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'recomp', 'gen')
for f in glob.glob(os.path.join(GEN, 'recomp_0*.c')):
    for m in re.finditer(r'/\* 0x([0-9A-F]{8}): ([^*]*)\*/', open(f).read()):
        ins[int(m[1], 16)] = m[2].strip()
ks = sorted(ins)
# The dirty grid (0x4C671D, 20 x 30 cells of 32x16): its marker keeps its 640x480 clip.
KEEP = {0x444D85, 0x444D9B, 0x444DA2, 0x444DD3, 0x444DE9, 0x444DF0}
idx = {a: i for i, a in enumerate(ks)}
def at(i): return ins[ks[i]] if 0 <= i < len(ks) else ''

W, H, VH, MUL = [], [], [], {}
for a in ks:
    s, i = ins[a], idx[a]
    if a in KEEP:
        continue
    if re.search(r'[-+] 0x(280|1e0|190)\]', s) or s.startswith(('and ', 'lea ')):
        continue                                   # stack/struct offsets, masks
    if re.search(r'\b0x280\b', s):
        ui = at(i + 1) == 'push eax' and at(i - 1) == 'push eax' and '0x1e0' not in at(i - 2) + at(i + 2)
        if not ui:
            W.append(a)
    if re.search(r'\b0x1e0\b', s):
        if not (at(i - 1).startswith('jmp') and '0x190' in at(i - 2)):   # the 320x200 branch's value
            H.append(a)
    if re.search(r'\b0x190\b', s):
        prev = ' '.join(at(j) for j in range(i - 3, i))
        if ('0x4ce5f6], 1' in prev and at(i - 1).startswith('je')) or a == 0x445FAE:
            VH.append(a)
# Row multiples: the 16-row unrolled copy, the 30-strip loop, the panel clear.
for a in ks:
    if 0x445C24 <= a < 0x445D90:
        m = re.search(r'\b0x([0-9a-f]+)\b', ins[a])
        if m and int(m[1], 16) % 640 == 0 and int(m[1], 16) > 640:
            MUL[a] = ('0x%Xu' % int(m[1], 16), '%d * tp_w' % (int(m[1], 16) // 640))
MUL[0x444F06] = ('0x2800u', '16 * tp_w')
MUL[0x445FB6] = ('0x3200u', 'tp_w * 20')
MUL[0x444EF5] = ('0x1Eu', '(tp_h + 15) / 16')         # strips of 16 rows
MUL[0x471CC2] = ('0xA0u', 'tp_w / 4')                  # rows of dwords: the screen copy
MUL[0x4715C5] = ('0xA0u', 'tp_w / 4')                  # and the fill
MUL[0x470E30] = ('0x50u', 'tp_w / 8')                  # copy in row pairs (640x480 only)
MUL[0x470F23] = ('0xFFFFF884u', '4 - 3 * tp_w')          # the fonts: back to the next character's top
MUL[0x470FC9] = ('0xFFFFF104u', '4 - 6 * tp_w')

def block(lst, const, var):
    out = ['SCREEN_SITES.update({a: (%r, %r) for a in (' % (const, var)]
    for k in range(0, len(lst), 8):
        out.append('    ' + ', '.join('0x%08X' % a for a in lst[k:k + 8]) + ',')
    out.append(')})')
    return '\n'.join(out)
print('# generated by tools/screen_sites.py: %d width, %d height, %d view-height, %d row-multiple sites'
      % (len(W), len(H), len(VH), len(MUL)))
print('SCREEN_SITES = {}')
print(block(W, '0x280u', 'tp_w'))
print(block(H, '0x1E0u', 'tp_h'))
print(block(VH, '0x190u', 'tp_vh'))
print('SCREEN_SITES.update({')
for a, (c, v) in sorted(MUL.items()):
    print('    0x%08X: (%r, %r),' % (a, c, v))
print('})')
# The fifth bank of the unrolled full-screen copies and the clear: a host call.
print('SCREEN_SITES.update({')
for a in (0x004023C0, 0x0040AF68, 0x0040B7AF, 0x004298BE, 0x00436CF2, 0x00436E5A, 0x00445B57, 0x00471D5D):
    print("    0x%08X: ('ecx = 0x2C00u;', '@tp_present_tail')," % a)
print("    0x00446061: ('ecx = 0x2C00u;', '@tp_clear_tail'),")
print('})')
